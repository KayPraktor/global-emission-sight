import React, { useState } from 'react';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { 
  FileText, 
  Download, 
  Eye, 
  Settings, 
  TrendingDown,
  TrendingUp,
  BarChart3,
  ArrowRight,
  CheckCircle2,
  Loader2,
  Target
} from 'lucide-react';
import { getExecutiveSummary } from '@/services/boardReportingService';
import { ProfessionalPDFGenerator, BrandingConfig } from '@/services/professionalPDFGenerator';
import { BoardReportPreview } from './BoardReportPreview';
import { useAuth } from '@/contexts/AuthContext';
import { useQuery } from '@tanstack/react-query';
import { 
  ResponsiveContainer,
  PieChart as RechartsPie,
  Pie,
  Cell,
  Legend,
  Tooltip
} from 'recharts';
import { toast } from 'sonner';
import { format } from 'date-fns';

const COLORS = ['hsl(var(--primary))', 'hsl(var(--chart-2))', 'hsl(var(--chart-3))'];

const DEFAULT_SECTIONS: Record<string, boolean> = {
  'Executive Summary': true,
  'Emissions Performance': true,
  'Target Progress': true,
  'Risk Assessment': true,
  'Opportunities': true,
  'Governance Scorecard': true,
  'Regulatory Updates': false,
  'Recommendations': true,
};

export const ExecutiveReportBuilder: React.FC = () => {
  const { organization } = useAuth();
  const orgId = organization?.id;
  const [selectedReportType, setSelectedReportType] = useState<'quarterly' | 'annual' | 'special'>('quarterly');
  const [sections, setSections] = useState<Record<string, boolean>>(DEFAULT_SECTIONS);
  const [isExporting, setIsExporting] = useState(false);
  const [isGenerating, setIsGenerating] = useState(false);
  const [previewOpen, setPreviewOpen] = useState(false);

  const { data: summary, isLoading } = useQuery({
    queryKey: ['board-executive-summary', orgId],
    queryFn: () => getExecutiveSummary(orgId!),
    enabled: !!orgId,
  });

  const toggleSection = (name: string) => {
    setSections(prev => ({ ...prev, [name]: !prev[name] }));
  };

  const handleExportPDF = () => {
    if (!summary) {
      toast.error('No data available to export');
      return;
    }
    setIsExporting(true);
    try {
      const branding: BrandingConfig = {
        companyName: 'Your Company',
        primaryColor: '#2563eb',
        secondaryColor: '#7c3aed',
        footerText: 'Confidential — Generated by Baryon ESG Platform',
      };
      const pdf = new ProfessionalPDFGenerator(branding);
      const dateStr = format(new Date(), 'MMMM yyyy');
      const typeLabel = selectedReportType.charAt(0).toUpperCase() + selectedReportType.slice(1);

      pdf.createCoverPage(`${typeLabel} Board Report`, 'Sustainability & Climate Performance', dateStr, `${typeLabel} Report`);

      if (sections['Executive Summary']) {
        pdf.addSection('Executive Summary');
        pdf.addMetricsRow([
          { label: 'Total Emissions', value: summary.currentEmissions.total.toLocaleString(), unit: 'tCO2e', change: `${summary.currentEmissions.change}% YoY`, changeType: summary.currentEmissions.change < 0 ? 'positive' : 'negative' },
          { label: 'Scope 1', value: summary.currentEmissions.scope1.toLocaleString(), unit: 'tCO2e' },
          { label: 'Scope 2', value: summary.currentEmissions.scope2.toLocaleString(), unit: 'tCO2e' },
          { label: 'Scope 3', value: summary.currentEmissions.scope3.toLocaleString(), unit: 'tCO2e' },
        ]);
        pdf.addKeyValueSection([
          { label: 'Year-over-Year Change', value: `${summary.currentEmissions.change}%`, highlight: summary.currentEmissions.change < 0 },
        ]);
      }

      pdf.finalize(`board-report-${selectedReportType}-${format(new Date(), 'yyyy-MM-dd')}.pdf`);
      toast.success('PDF exported', { description: 'Board report downloaded.' });
    } catch (e) {
      toast.error('Export failed', { description: String(e) });
    } finally {
      setIsExporting(false);
    }
  };

  const handleGenerateReport = () => {
    const enabledCount = Object.values(sections).filter(Boolean).length;
    if (enabledCount === 0) {
      toast.error('No sections selected', { description: 'Please select at least one section to include.' });
      return;
    }
    handleExportPDF();
  };

  if (isLoading) {
    return (
      <div className="flex items-center justify-center h-64">
        <Loader2 className="w-8 h-8 animate-spin text-primary" />
      </div>
    );
  }

  const emissionsBreakdown = summary ? [
    { name: 'Scope 1', value: summary.currentEmissions.scope1 },
    { name: 'Scope 2', value: summary.currentEmissions.scope2 },
    { name: 'Scope 3', value: summary.currentEmissions.scope3 },
  ] : [];

  const hasEmissions = summary && summary.currentEmissions.total > 0;

  return (
    <div className="space-y-6">
      <BoardReportPreview
        open={previewOpen}
        onOpenChange={setPreviewOpen}
        summary={summary || null}
        sections={sections}
        reportType={selectedReportType}
        onDownloadPDF={handleExportPDF}
      />

      {/* Report Type Selection */}
      <Card>
        <CardHeader>
          <div className="flex items-center justify-between">
            <div>
              <CardTitle className="flex items-center gap-2">
                <FileText className="h-5 w-5 text-primary" />
                Executive Report Builder
              </CardTitle>
              <CardDescription>Generate board-ready sustainability reports</CardDescription>
            </div>
            <div className="flex gap-2">
              <Button variant="outline" size="sm" onClick={() => setPreviewOpen(true)}>
                <Eye className="h-4 w-4 mr-1" /> Preview
              </Button>
              <Button size="sm" onClick={handleExportPDF} disabled={isExporting || !hasEmissions}>
                {isExporting ? <Loader2 className="h-4 w-4 mr-1 animate-spin" /> : <Download className="h-4 w-4 mr-1" />}
                Export PDF
              </Button>
            </div>
          </div>
        </CardHeader>
        <CardContent>
          <Tabs value={selectedReportType} onValueChange={(v) => setSelectedReportType(v as any)}>
            <TabsList className="grid grid-cols-3 w-full max-w-md">
              <TabsTrigger value="quarterly">Quarterly</TabsTrigger>
              <TabsTrigger value="annual">Annual</TabsTrigger>
              <TabsTrigger value="special">Special</TabsTrigger>
            </TabsList>
          </Tabs>
        </CardContent>
      </Card>

      {/* Executive Summary */}
      {hasEmissions ? (
        <Card className="bg-gradient-to-br from-slate-50 to-slate-100 dark:from-slate-900 dark:to-slate-800">
          <CardHeader>
            <CardTitle>Executive Summary</CardTitle>
            <CardDescription>Key metrics and highlights for board presentation</CardDescription>
          </CardHeader>
          <CardContent className="space-y-6">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
              <div className="p-4 bg-background rounded-lg border">
                <h4 className="font-semibold mb-4 flex items-center gap-2">
                  <BarChart3 className="h-4 w-4 text-primary" />
                  Current Emissions
                </h4>
                <div className="text-3xl font-bold mb-2">
                  {summary!.currentEmissions.total.toLocaleString()}
                  <span className="text-lg font-normal text-muted-foreground ml-1">tCO2e</span>
                </div>
                <div className="flex items-center gap-2 mb-4">
                  <Badge variant={summary!.currentEmissions.change < 0 ? 'default' : 'destructive'}>
                    {summary!.currentEmissions.change < 0 ? <TrendingDown className="h-3 w-3 mr-1" /> : <TrendingUp className="h-3 w-3 mr-1" />}
                    {Math.abs(summary!.currentEmissions.change)}% YoY
                  </Badge>
                </div>
                <div className="h-[180px]">
                  <ResponsiveContainer width="100%" height="100%">
                    <RechartsPie>
                      <Pie data={emissionsBreakdown} cx="50%" cy="50%" innerRadius={40} outerRadius={70} paddingAngle={2} dataKey="value">
                        {emissionsBreakdown.map((_, index) => (
                          <Cell key={`cell-${index}`} fill={COLORS[index % COLORS.length]} />
                        ))}
                      </Pie>
                      <Legend />
                      <Tooltip formatter={(value: number) => [`${value.toLocaleString()} tCO2e`, '']} />
                    </RechartsPie>
                  </ResponsiveContainer>
                </div>
              </div>

              {summary!.targets.shortTerm && (
                <div className="p-4 bg-background rounded-lg border">
                  <h4 className="font-semibold mb-4 flex items-center gap-2">
                    <Target className="h-4 w-4 text-primary" />
                    Reduction Target
                  </h4>
                  <div className="text-2xl font-bold mb-1">
                    {summary!.targets.shortTerm.reduction}% <span className="text-sm font-normal text-muted-foreground">reduction by {summary!.targets.shortTerm.year}</span>
                  </div>
                  <p className="text-sm text-muted-foreground">
                    Current progress: {summary!.targets.shortTerm.current}%
                  </p>
                </div>
              )}
            </div>
          </CardContent>
        </Card>
      ) : (
        <Card className="text-center py-12">
          <CardContent>
            <BarChart3 className="h-12 w-12 mx-auto text-muted-foreground mb-4" />
            <h3 className="text-lg font-semibold mb-2">No Emissions Data</h3>
            <p className="text-muted-foreground">Add emissions data to generate executive reports.</p>
          </CardContent>
        </Card>
      )}

      {/* Report Sections */}
      <Card>
        <CardHeader>
          <CardTitle className="text-lg">Report Sections</CardTitle>
          <CardDescription>Customize which sections to include in the board report</CardDescription>
        </CardHeader>
        <CardContent>
          <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
            {Object.entries(sections).map(([name, included]) => (
              <div
                key={name}
                onClick={() => toggleSection(name)}
                className={`p-3 border rounded-lg flex items-center gap-2 cursor-pointer transition-colors ${
                  included ? 'bg-primary/5 border-primary/30' : 'bg-muted/30 hover:bg-muted/50'
                }`}
              >
                <CheckCircle2 className={`h-4 w-4 ${included ? 'text-primary' : 'text-muted-foreground'}`} />
                <span className="text-sm">{name}</span>
              </div>
            ))}
          </div>

          <div className="flex justify-end gap-3 mt-6">
            <Button variant="outline" onClick={() => toast.info('Toggle the checkboxes above to include or exclude report sections.')}>
              <Settings className="h-4 w-4 mr-2" />
              Customize
            </Button>
            <Button onClick={handleGenerateReport} disabled={isGenerating || !hasEmissions}>
              {isGenerating ? <Loader2 className="h-4 w-4 mr-2 animate-spin" /> : null}
              Generate Report
              {!isGenerating && <ArrowRight className="h-4 w-4 ml-2" />}
            </Button>
          </div>
        </CardContent>
      </Card>
    </div>
  );
};
