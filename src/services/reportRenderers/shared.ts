import { ProfessionalPDFGenerator } from '../professionalPDFGenerator';
import { Template, TemplateData } from '../templateService';

export const createPDFWithCover = (template: Template, data: TemplateData): ProfessionalPDFGenerator => {
  const branding = {
    companyName: data.companyName,
    primaryColor: '#059669',
    secondaryColor: '#2563eb',
    headerText: 'Confidential – For Internal and Regulatory Use Only',
    footerText: `Generated by BARYON · Prepared by ${data.preparedBy}`,
  };

  const pdf = new ProfessionalPDFGenerator(branding);

  pdf.createCoverPage(
    template.title,
    data.reportingPeriod,
    data.reportDate,
    `${data.verificationStatus} · ${data.reportingBoundary}`
  );

  return pdf;
};

export const finalizePDF = (pdf: ProfessionalPDFGenerator): Blob => {
  const doc = pdf.getDoc();
  return new Blob([doc.output('blob')], { type: 'application/pdf' });
};
