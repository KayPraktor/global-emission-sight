// Convert English numbers to Persian numerals
export function toPersianNumber(num: number | string): string {
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return String(num).replace(/[0-9]/g, (d) => persianDigits[parseInt(d)]);
}

// Format number with Persian numerals and thousands separator
export function formatPersianNumber(num: number, decimals: number = 1): string {
  const formatted = num.toFixed(decimals);
  const parts = formatted.split('.');
  const integerPart = parts[0].replace(/\B(?=(\d{3})+(?!\d))/g, '،');
  const result = parts.length > 1 ? `${integerPart}.${parts[1]}` : integerPart;
  return toPersianNumber(result);
}

